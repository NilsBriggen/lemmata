#!/usr/bin/env python3
"""Generate data/pkgmap.tsv.gz from TeX Live's package database.

Each line is `file<TAB>package<TAB>collection` for the files a document can
ask for by name (.sty, .cls, .bst and biblatex styles). lemmata-pkgmap turns
the collection or package into the install command for the user's system.

Usage:
  scripts/gen-pkgmap.py                 download the current tlpdb from CTAN
  scripts/gen-pkgmap.py texlive.tlpdb   use a local copy
"""

import gzip
import lzma
import sys
import urllib.request
from pathlib import Path

TLPDB_URL = "https://mirror.ctan.org/systems/texlive/tlnet/tlpkg/texlive.tlpdb.xz"
EXTENSIONS = (".sty", ".cls", ".bst", ".bbx", ".cbx", ".lbx")
OUT = Path(__file__).resolve().parent.parent / "data" / "pkgmap.tsv.gz"


def records(text: str):
    for block in text.split("\n\n"):
        lines = block.splitlines()
        if lines and lines[0].startswith("name "):
            yield lines


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        print(f"downloading {TLPDB_URL}")
        with urllib.request.urlopen(TLPDB_URL) as r:
            text = lzma.decompress(r.read()).decode("utf-8")

    files: dict[str, str] = {}
    collection_of: dict[str, str] = {}
    release = "unknown"

    for lines in records(text):
        name = lines[0][5:].strip()
        if name == "00texlive.config":
            release = next((l.split()[-1] for l in lines if l.startswith("depend release/")), release)
        if name.startswith("collection-"):
            for l in lines:
                if l.startswith("depend "):
                    collection_of.setdefault(l[7:].strip(), name)
            continue
        in_runfiles = False
        for l in lines:
            if l.startswith("runfiles"):
                in_runfiles = True
                continue
            if in_runfiles and l.startswith(" "):
                path = l.strip().split(" ")[0]
                base = path.rsplit("/", 1)[-1]
                if base.endswith(EXTENSIONS):
                    # First package wins; duplicates are rare forks of the same file.
                    files.setdefault(base, name)
            elif in_runfiles:
                in_runfiles = False

    rows = [f"{f}\t{p}\t{collection_of.get(p, '')}" for f, p in sorted(files.items())]
    header = f"# TeX Live {release} file -> package -> collection, generated by scripts/gen-pkgmap.py\n"
    OUT.write_bytes(gzip.compress((header + "\n".join(rows) + "\n").encode(), mtime=0))
    print(f"wrote {len(rows)} files to {OUT} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
