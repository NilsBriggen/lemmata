// Writes apps/lemmata/src/icons_data.rs: every Lucide icon the Svelte UI imports, as SVG path data.
// Run from the repo root after `pnpm install`: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = "apps/desktop/src";
const lucide = "apps/desktop/node_modules/@lucide/svelte/dist/icons";

const walk = (d) =>
  readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
const names = new Set();
for (const f of walk(src))
  for (const m of readFileSync(f, "utf8").matchAll(/@lucide\/svelte\/icons\/([a-z0-9-]+)/g)) names.add(m[1]);

// Every element becomes a path, so the app needs one parser.
const n = (v, d = 0) => (v === undefined ? d : Number(v));
function toPath([tag, a]) {
  switch (tag) {
    case "path":
      return a.d;
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon":
      return "M" + a.points.trim().split(/[\s,]+/).reduce((s, v, i) => s + (i && i % 2 === 0 ? "L" : " ") + v, "").trim() + (tag === "polygon" ? "Z" : "");
    case "circle":
    case "ellipse": {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx ?? a.r), ry = n(a.ry ?? a.r);
      return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
    }
    case "rect": {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    default:
      throw new Error(`unknown element ${tag}`);
  }
}

// Some imports are aliases (history -> rotate-ccw-clock) with no .svelte file of their own.
const icons = new Map();
for (const f of readdirSync(lucide).filter((f) => f.endsWith(".svelte"))) {
  const data = JSON.parse(readFileSync(join(lucide, f), "utf8").match(/const iconData = (\{.*\});/)[1]);
  for (const key of [data.name, ...(data.aliases ?? [])]) icons.set(key, data);
}

let out = "// Generated by scripts/gen-icons.mjs from @lucide/svelte (ISC licence). Do not edit.\n\n";
for (const name of [...names].sort()) {
  const data = icons.get(name);
  if (!data) throw new Error(`no lucide icon ${name}`);
  const paths = data.node.map(toPath).map((d) => JSON.stringify(d)).join(", ");
  out += `pub const ${name.toUpperCase().replaceAll("-", "_")}: &[&str] = &[${paths}];\n`;
}
writeFileSync("apps/lemmata/src/icons_data.rs", out);
console.log(`${names.size} icons`);
