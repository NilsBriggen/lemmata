#!/usr/bin/env python3
"""Builds design/mockups/*.html from design/mockups/src: expands <!-- @include name k=v --> partials
and inlines Lucide icons (<i data-i="NAME" class="..."></i>) from apps/lemmata/src/icons_data.rs."""
import pathlib, re, shutil
D = pathlib.Path(__file__).resolve().parent
SRC, OUT = D / 'mockups/src', D / 'mockups'
data = (D.parent / 'apps/lemmata/src/icons_data.rs').read_text()
ICONS = {m[1]: re.findall(r'"([^"]*)"', m[2]) for m in re.finditer(r'pub const (\w+): &\[&str\] = &\[(.*?)\];', data)}

def include(m):
    name, *args = m[1].split()
    text = (SRC / 'partials' / name).read_text()
    for k, v in (a.split('=', 1) for a in args):
        text = text.replace('{' + k + '}', v)
    return text

def icon(m):
    cls = f' {m[3]}' if m[3] else ''
    return f'<svg class="i{cls}" viewBox="0 0 24 24" aria-hidden="true">' + ''.join(f'<path d="{d}"/>' for d in ICONS[m[1]]) + '</svg>'

for page in SRC.glob('*.html'):
    html = re.sub(r'<!-- @include (.*?) -->\n?', include, page.read_text())
    html = re.sub(r'<i data-i="(\w+)"( class="([\w -]+)")?></i>', icon, html)
    assert 'data-i=' not in html, page
    (OUT / page.name).write_text(html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by design/build.py from mockups/src; edit the source. -->', 1))
shutil.copy(SRC / 'base.css', OUT / 'base.css')
print('built', sorted(p.name for p in SRC.glob('*.html')))
